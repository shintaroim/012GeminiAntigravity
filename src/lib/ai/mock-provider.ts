import { ProgramPhase } from "@/types";
import { AIProvider, AIRequest, AIResponse } from "./provider";

export interface MockAiOptions {
  message: string;
  turnCount: number;
  phase?: ProgramPhase;
}

export function generateMockAiResponse(options: MockAiOptions): string {
  const trimmed = options.message.trim();
  const lower = trimmed.toLowerCase();

  // 1. 初回導入または「ほんね」
  if (options.turnCount === 0 || lower === "ほんね") {
    return (
      "スタートおめでとうございます。\n\n" +
      "ここでは最初から『本にする話』を考えなくて大丈夫です。\n" +
      "人生をきれいにまとめる必要もありません。\n" +
      "思い出したことを、そのまま話してください。\n\n" +
      "私はあなたの話の中から、何度も出てくる言葉、人生を動かした出来事、当時は大したことないと思っていたけれど今のあなたにつながっている経験、そして、あなたが人生の中で何を選んできたのかを、一緒に拾っていきます。\n\n" +
      "私があなたの答えを決めることはありません。いくつかの可能性を差し出します。『違う』と思ったら、遠慮なく違うと言ってください。\n\n" +
      "最後には、『私をつくった7つの物語』と『迷ったときに戻れる3つの問い』を一緒に見つけます。でも今は、そこを考えなくて大丈夫です。\n\n" +
      "安心して話せるように、ご家族やお知り合いは『夫』『長男』『友人A』のような呼び名で、住所や勤務先など個人が特定できることは話さなくて大丈夫です。\n\n" +
      "まず、今のあなたから話してみましょう。\n\n" +
      "最近ふと、『このままでいいのかな』とか、『これから私はどうしたいんだろう』と思ったことはありますか？ 大きな悩みじゃなくて大丈夫です。"
    );
  }

  // 2. 「たたき台をまとめて」
  if (trimmed.includes("たたき台をまとめて")) {
    return (
      "━━━━━━━━━━━━━━\n" +
      "HON-NEo「話す」のたたき台（保存用）\n" +
      "━━━━━━━━━━━━━━\n" +
      "■ 7 STORIES候補（10〜15個）\n" +
      "1｜出来事の仮名：転機となった最初の選択\n" +
      "　何が起きたか：周囲の反対を押し切って新しい環境へ飛び込んだこと\n" +
      "　今の私につながっていると思う理由：自分で選んだ責任を知った原点\n" +
      "　本人の原文：「あのときは無我夢中だった」\n" +
      "2｜出来事の仮名：挫折と立ち止まり\n" +
      "　何が起きたか：体調を崩して休養した期間\n" +
      "　今の私につながっていると思う理由：無理を続ける生き方をやめた\n" +
      "　本人の原文：「立ち止まるのが怖かったけれど、止まってよかった」\n\n" +
      "■ 3 COMPASS候補（5〜7個）\n" +
      "・自分で決める自由（根拠になった出来事：最初の転職）\n" +
      "・心と身体の声を聞く（根拠になった出来事：休養期間）\n\n" +
      "■ 本人の象徴的な原文\n" +
      "・「誰かのせいにはしたくなかった」\n" +
      "・「自分の声だけは裏切りたくない」\n\n" +
      "■ 選ばなかった言葉\n" +
      "・単なる成功物語 →「そういうカッコいいものじゃない」と本人\n\n" +
      "■ まだ決めたくないところ\n" +
      "・当時の周囲への感情の整理\n" +
      "━━━━━━━━━━━━━━\n\n" +
      "このたたき台を、スマホのメモなどにコピーして保存しておいてください。\n" +
      "ここから1週間は、何もしなくて大丈夫です。日常の中で『これ、私っぽい』『ちょっと違う』と感じたら、覚えておくだけでOKです。\n" +
      "WEEK 3の『整える』は、新しいチャットで『整える』と送り、このたたき台を貼り付けてください。"
    );
  }

  // 3. 「整える」
  if (trimmed.startsWith("整える") || trimmed.includes("整える")) {
    return (
      "おかえりなさい。寝かせている間に、気づいたことや、『これはちょっと違うかも』と感じたことはありましたか？\n\n" +
      "日常の中でふと思い出したことや、たたき台を見て感じた違和感があれば、まずはそこから教えてください。"
    );
  }

  // 4. 「寝かせる」期間の対話
  if (options.phase === "rest" || trimmed.includes("寝かせる")) {
    return (
      "大切な気づきですね。\n\n" +
      "寝かせる期間は、無理に深く考えなくて大丈夫です。日常を過ごしながら、その感覚をそっと覚えておいてください。\n" +
      "その気づきは、WEEK 3の『整える』のときにぜひ持ってきてくださいね。"
    );
  }

  // 5. 「BOOK SEEDをまとめて」
  if (
    trimmed.includes("BOOK SEEDをまとめて") ||
    trimmed.includes("book seedをまとめて") ||
    trimmed.includes("ブックシードをまとめて")
  ) {
    return (
      "━━━━━━━━━━━━━━\n" +
      "BOOK SEED｜わたしの物語（仮）\n" +
      "━━━━━━━━━━━━━━\n" +
      "■ MY 7 STORIES｜私をつくった7つの物語\n\n" +
      "STORY 1\n" +
      "《怖いまま、あのドアを開けた》\n" +
      "元になった出来事：最初のキャリアチェンジ\n" +
      "■ 何があったか：安定した道を離れ、未経験の分野へ飛び込んだ\n" +
      "■ 当時の私：不安で眠れなかった\n" +
      "■ 本当はどう感じていたか：他人のレールの上で生きたくなかった\n" +
      "■ 私が選んだこと：自分で決めること\n" +
      "■ 私が選ばなかったこと：周囲の期待に応え続けること\n" +
      "■ 今振り返って思うこと：あのときの選択が今の私をつくった\n" +
      "■ この出来事が私に残したもの：自分の人生を自分で選ぶ覚悟\n" +
      "■ 本人の象徴的な原文：「あのときは無我夢中だった」\n" +
      "■ つながるCOMPASS：COMPASS 1\n\n" +
      "■ MY 3 COMPASS｜迷ったときに戻れる3つの問い\n\n" +
      "COMPASS 1\n" +
      "《自分で選べる自由》\n" +
      "私にとって自分で選べる自由とは、他人の正解ではなく、失敗しても自分で納得して引き受けること。\n" +
      "なぜなら私は、STORY 1などで、安定よりも自分で決めるという選択をしてきたから。\n" +
      "これから迷ったとき、私は自分にこう問いかける。\n" +
      "「これは、私が自分で選びたいことだろうか？」\n\n" +
      "■ 私の人生の再定義\n" +
      "私は、周囲の目を気にしながらも、最後には自分の声を選び直してきた人生を生きてきた。\n" +
      "7つの物語を振り返ると、私は何度も、『自分で納得して決めること』を選んできた。\n" +
      "だからこれからは、3つのCOMPASSを持って、自分で自分の航路を選んで生きていく。\n\n" +
      "■ 次のタネ箱\n" +
      "・幼少期の引越しでの経験（今回は7つに入らなかったけれど、大切な変化の記憶）\n" +
      "━━━━━━━━━━━━━━\n\n" +
      "私から見ると、あなたの7つの物語と3つのCOMPASSは、かなり揃ったように見えます。でも、完成を決めるのは私ではありません。\n\n" +
      "これを読んで、『これは私だ』と言えますか？"
    );
  }

  // 6. 「まとめて」または「今どんな感じ？」
  if (trimmed.includes("まとめて") || trimmed.includes("今どんな感じ？")) {
    return (
      "【⚓ HON-NEoまとめログ】\n\n" +
      `■ 今回印象に残った本人の言葉：「${trimmed.slice(0, 30)}」\n` +
      "■ 見えてきた出来事：\n" +
      "・日常の違和感から始まった変化\n" +
      "■ 何度か現れているもの：\n" +
      "・『自分で納得したい』という姿勢\n" +
      "■ 価値観の仮説：\n" +
      "A｜自分で選ぶこと　B｜誠実さ\n" +
      "■ 7 STORIES候補：\n" +
      "・あのとき踏みとどまった日のこと\n" +
      "■ まだ決めたくないところ：\n" +
      "・周囲との関係性の捉え方\n\n" +
      "ここまでで、『それは違う』と思うところはありますか？"
    );
  }

  // 7. 通常の対話ターン（1ターン1問の深掘り）
  return (
    `「${trimmed.slice(0, 24)}${trimmed.length > 24 ? "…" : ""}」という言葉が印象に残りました。\n\n` +
    "そのとき、胸の中ではどんな気持ちが一番強かったですか？"
  );
}

export class MockAIProvider implements AIProvider {
  public name = "mock";

  async generateResponse(request: AIRequest): Promise<AIResponse> {
    const lastUserMessage = [...request.messages]
      .reverse()
      .find((m) => m.role === "user");

    const userText = lastUserMessage?.content || "ほんね";
    const turnCount = request.messages.filter((m) => m.role === "assistant").length;

    const content = generateMockAiResponse({
      message: userText,
      turnCount,
    });

    return {
      content,
      model: "mock-model",
      inputTokens: 150,
      outputTokens: 120,
    };
  }
}
